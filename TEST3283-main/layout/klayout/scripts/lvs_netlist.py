"""Schematic netlist of TEST3283 for LVS, from slots.csv.

  python3 scripts/lvs_netlist.py slots.csv <out.cdl>

One cap_cmomi per placed cell, between the tile's PLUS (left signal pad) and MINUS (right signal pad) nets;
the copies of an array are separate instances on the same two nets. OP, SHT, TH, LS and the ground frame
hold no device, so they have no schematic counterpart (the LVS run purges device-free nets).

The cmos5l deck matches cap_cmomi topologically: it checks the devices (array copies included) and the nets,
not w, l, mmin, mmax or feed (lvs/testing/README.md of the PDK). They are written anyway so the netlist
documents the chip.
"""
import csv
import sys

slots, out = sys.argv[1], sys.argv[2]
lines = ["* TEST3283 schematic netlist for LVS, generated by scripts/lvs_netlist.py from slots.csv.",
         "* Bk_P: left signal pad (PLUS), Bk_M: right signal pad (MINUS) of tile Bk.",
         ".SUBCKT TEST3283"]
n = 0
for s in csv.DictReader(open(slots)):
    for k in range(int(s["mult"])):
        n += 1
        lines.append(f"C{s['tile']}_{k + 1} {s['tile']}_P {s['tile']}_M cap_cmomi "
                     f"w={float(s['w_um'])}e-06 l={float(s['l_um'])}e-06 "
                     f"mmin={s['mmin']} mmax={s['mmax']} feed={s['feed']}")
lines.append(".ENDS TEST3283")
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", out, n, "devices")
